// Package graph is the extension-facing API of Gazelle's build graph: an
// immutable, deterministic graph of build entities (targets, external
// targets, source files, generated files, and importable names) connected
// by typed edges.
//
// EXPERIMENTAL: the build graph is used only when Gazelle v2 runs with
// -experimental_build_graph. This package may change without a major
// version bump until the feature is stable.
//
// Gazelle builds the graph in phases:
//
//  1. Collect: Gazelle adds a node for every rule in each build file it
//     visits, plus edges for attributes it understands. Extensions
//     implementing [Contributor] add facts through a package-scoped [Facts]
//     sink, mainly the imports each rule requires.
//  2. Link: Gazelle replaces each Requires fact with [DependsOn] edges to the
//     import's providers ([LinkPolicy] customizes this).
//  3. Freeze and validate: the graph becomes immutable, and Gazelle reports
//     dependency cycles ([Graph.Cycles]).
//  4. Materialize: extensions implementing [Materializer] set rule
//     attributes from graph queries.
//
// Vertices are identified by canonical string keys ([NodeKey]). Edges are
// values of dedicated types. Extensions don't traverse edges directly; they
// call query methods like [Graph.DirectDeps] and [Graph.Providers].
//
// The implementation lives in an internal package; the types here are
// aliases, so their methods are documented there.
package graph

import (
	"github.com/bazel-contrib/bazel-gazelle/v2/internal/graph/model"
	"github.com/bazel-contrib/bazel-gazelle/v2/label"
	"github.com/bazel-contrib/bazel-gazelle/v2/resolve"
)

// Keys and nodes.
type (
	// NodeKey is the canonical string identity of a vertex, like
	// "t:@@//pkg:name". See [TargetKey] and friends.
	NodeKey = model.NodeKey
	// KeyInfo is the parsed form of a NodeKey; see [ParseKey].
	KeyInfo = model.KeyInfo
	// Node is a vertex.
	Node = model.Node
	// NodeKind classifies vertices.
	NodeKind = model.NodeKind
	// Origin records where a fact came from: a bit set of Origin* values.
	Origin = model.Origin
	// ImportSpec is an importable name in a language namespace.
	ImportSpec = resolve.ImportSpec
)

const (
	KindTarget        = model.KindTarget
	KindExternal      = model.KindExternal
	KindSourceFile    = model.KindSourceFile
	KindGeneratedFile = model.KindGeneratedFile
	KindImport        = model.KindImport

	OriginExisting  = model.OriginExisting
	OriginGenerated = model.OriginGenerated
	OriginIndexed   = model.OriginIndexed
	OriginExternal  = model.OriginExternal
	OriginKeep      = model.OriginKeep
)

// TargetKey returns the key for a rule target. l must be absolute.
func TargetKey(l label.Label) NodeKey { return model.TargetKey(l) }

// SourceFileKey returns the key for a checked-in source file.
func SourceFileKey(l label.Label) NodeKey { return model.SourceFileKey(l) }

// GeneratedFileKey returns the key for a file generated by a rule.
func GeneratedFileKey(l label.Label) NodeKey { return model.GeneratedFileKey(l) }

// ImportKey returns the key for an importable name.
func ImportKey(imp ImportSpec) NodeKey { return model.ImportKey(imp) }

// ParseKey parses and validates a key.
func ParseKey(k NodeKey) (KeyInfo, error) { return model.ParseKey(k) }

// Edges.
type (
	// Edge is implemented by every edge type. It can't be implemented
	// outside Gazelle; use ExtensionEdge for extension-defined edges.
	Edge = model.Edge
	// EdgeKind names a type of edge.
	EdgeKind = model.EdgeKind
	// DependsOn means From needs To at build time through an attribute.
	DependsOn = model.DependsOn
	// Requires means a target imports an importable name; see Facts.Requires.
	Requires = model.Requires
	// ExtensionEdge is an extension-defined edge; its kind must be declared
	// in an EdgeSchema.
	ExtensionEdge = model.ExtensionEdge
	// EdgeSchema declares an extension-defined edge kind.
	EdgeSchema = model.EdgeSchema
)

const (
	KindDependsOn = model.KindDependsOn
	KindProvides  = model.KindProvides
	KindRequires  = model.KindRequires
	KindEmbeds    = model.KindEmbeds
	KindContains  = model.KindContains
	KindGenerates = model.KindGenerates
	KindAliasOf   = model.KindAliasOf
	KindExports   = model.KindExports
)

// Graph and queries.
type (
	// Graph is an immutable build graph. All methods are safe for
	// concurrent use and return deterministic, sorted results.
	Graph = model.Graph
	// DepQuery filters DependsOn edges.
	DepQuery = model.DepQuery
	// SelectFilter filters dependencies by select() key.
	SelectFilter = model.SelectFilter
	// Dep is a dependency returned by DirectDeps and DirectRdeps.
	Dep = model.Dep
	// ExtensionDep is an extension edge returned by
	// Graph.ExtensionNeighbors.
	ExtensionDep = model.ExtensionDep
	// Direction selects incoming or outgoing edges.
	Direction = model.Direction
	// UnresolvedImport is a required import that linking couldn't satisfy.
	UnresolvedImport = model.UnresolvedImport
	// Cycle is a group of targets that depend on each other.
	Cycle = model.Cycle
	// CycleEdge is one step of a Cycle's path.
	CycleEdge = model.CycleEdge
	// CycleError reports a dependency cycle; it wraps ErrCycle.
	CycleError = model.CycleError
	// Facts is a write-only sink for facts about one package.
	Facts = model.Facts
)

var (
	// AnySelect matches all dependencies (the zero SelectFilter).
	AnySelect = model.AnySelect
	// Unconditional matches only dependencies outside select().
	Unconditional = model.Unconditional
)

const (
	Out = model.Out
	In  = model.In
)

// SelectKey returns a SelectFilter matching dependencies under key.
func SelectKey(key string) SelectFilter { return model.SelectKey(key) }

// RelativeLabels converts dependencies to labels relative to from's
// package, sorted and without duplicates.
func RelativeLabels(deps []Dep, from label.Label) []label.Label {
	return model.RelativeLabels(deps, from)
}

// Errors. Errors returned by this package and reported by Gazelle wrap
// these.
var (
	ErrNonCanonicalKey  = model.ErrNonCanonicalKey
	ErrConflictingNode  = model.ErrConflictingNode
	ErrInvalidEdge      = model.ErrInvalidEdge
	ErrUnknownEdgeKind  = model.ErrUnknownEdgeKind
	ErrDuplicateOutput  = model.ErrDuplicateOutput
	ErrOutOfPackage     = model.ErrOutOfPackage
	ErrCycle            = model.ErrCycle
	ErrUnresolvedImport = model.ErrUnresolvedImport
	ErrAmbiguousImport  = model.ErrAmbiguousImport
)
