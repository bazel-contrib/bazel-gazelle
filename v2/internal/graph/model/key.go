package model

import (
	"fmt"
	"strings"

	"github.com/bazel-contrib/bazel-gazelle/v2/label"
	"github.com/bazel-contrib/bazel-gazelle/v2/resolve"
)

// NodeKey is the canonical, globally unique identity of a vertex. Two nodes
// are the same node if and only if their keys are byte-equal.
//
// Keys should be constructed with [TargetKey], [SourceFileKey],
// [GeneratedFileKey], or [ImportKey]. Keys built by hand are validated with
// [ParseKey] when added to a [Builder].
//
// Key formats:
//
//	t:<label>        rule target (main repo or external)
//	f:<label>        checked-in source file
//	g:<label>        generated file
//	i:<lang>:<imp>   importable name in a language namespace
//
// Labels in keys are always fully spelled: "@@//pkg:name" for the main
// repository, "@@repo//pkg:name" for canonical repo names, and
// "@repo//pkg:name" for apparent repo names. Gazelle does not apply repo
// mapping, so an apparent name and a canonical name are distinct keys.
type NodeKey string

const (
	targetPrefix    = "t:"
	sourcePrefix    = "f:"
	generatedPrefix = "g:"
	importPrefix    = "i:"
)

// ImportSpec describes an importable name in a language namespace.
type ImportSpec = resolve.ImportSpec

// TargetKey returns the key for a rule target. l must be absolute; a relative
// label produces an invalid key that the Builder rejects.
func TargetKey(l label.Label) NodeKey { return labelKey(targetPrefix, l) }

// SourceFileKey returns the key for a checked-in source file.
func SourceFileKey(l label.Label) NodeKey { return labelKey(sourcePrefix, l) }

// GeneratedFileKey returns the key for a file generated by a rule.
func GeneratedFileKey(l label.Label) NodeKey { return labelKey(generatedPrefix, l) }

// ImportKey returns the key for an importable name. imp.Lang must not
// contain ':'; otherwise the key doesn't parse back to imp. [Facts] rejects
// such imports.
func ImportKey(imp ImportSpec) NodeKey {
	return NodeKey(importPrefix + imp.Lang + ":" + imp.Imp)
}

func labelKey(prefix string, l label.Label) NodeKey {
	if l.Relative {
		return NodeKey(prefix + ":" + l.Name)
	}
	return NodeKey(prefix + canonicalLabel(l))
}

func canonicalLabel(l label.Label) string {
	var repo string
	switch {
	case l.Repo == "" || l.Repo == "@":
		repo = "@@"
	case l.Canonical:
		repo = "@@" + l.Repo
	default:
		repo = "@" + l.Repo
	}
	return repo + "//" + l.Pkg + ":" + l.Name
}

// KeyInfo is the parsed form of a NodeKey.
type KeyInfo struct {
	// Class is KindTarget, KindSourceFile, KindGeneratedFile, or KindImport.
	// Keys don't distinguish main-repo targets from external targets; use
	// IsMainRepo for that.
	Class NodeKind

	// Label is set for every class except KindImport.
	Label label.Label

	// Import is set for KindImport.
	Import ImportSpec
}

// IsMainRepo reports whether the key refers to an entity in the main
// repository.
func (k KeyInfo) IsMainRepo() bool {
	return k.Class != KindImport && (k.Label.Repo == "" || k.Label.Repo == "@")
}

// ParseKey parses and validates a key. It returns an error wrapping
// ErrNonCanonicalKey if the key is malformed or isn't in canonical form.
func ParseKey(k NodeKey) (KeyInfo, error) {
	s := string(k)
	var class NodeKind
	switch {
	case strings.HasPrefix(s, targetPrefix):
		class = KindTarget
	case strings.HasPrefix(s, sourcePrefix):
		class = KindSourceFile
	case strings.HasPrefix(s, generatedPrefix):
		class = KindGeneratedFile
	case strings.HasPrefix(s, importPrefix):
		rest := s[len(importPrefix):]
		lang, imp, ok := strings.Cut(rest, ":")
		if !ok || lang == "" || imp == "" {
			return KeyInfo{}, fmt.Errorf("%w: %q: want i:<lang>:<import>", ErrNonCanonicalKey, s)
		}
		return KeyInfo{Class: KindImport, Import: ImportSpec{Lang: lang, Imp: imp}}, nil
	default:
		return KeyInfo{}, fmt.Errorf("%w: %q: unknown prefix", ErrNonCanonicalKey, s)
	}
	rest := s[2:]
	l, err := label.Parse(rest)
	if err != nil {
		return KeyInfo{}, fmt.Errorf("%w: %q: %v", ErrNonCanonicalKey, s, err)
	}
	if l.Relative || canonicalLabel(l) != rest {
		return KeyInfo{}, fmt.Errorf("%w: %q: label must be written as %q", ErrNonCanonicalKey, s, canonicalLabel(l.Abs("", "")))
	}
	// Normalize the main repository to the empty repo name.
	if l.Repo == "@" || (l.Repo == "" && l.Canonical) {
		l.Repo, l.Canonical = "", false
	}
	return KeyInfo{Class: class, Label: l}, nil
}
