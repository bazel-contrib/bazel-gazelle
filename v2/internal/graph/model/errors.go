package model

import "errors"

var (
	// ErrNonCanonicalKey is wrapped by errors for malformed or non-canonical
	// node keys.
	ErrNonCanonicalKey = errors.New("non-canonical node key")

	// ErrConflictingNode is wrapped by errors for facts that give one key
	// incompatible kinds.
	ErrConflictingNode = errors.New("conflicting node")

	// ErrInvalidEdge is wrapped by errors for edges whose endpoints have
	// kinds the edge type doesn't allow.
	ErrInvalidEdge = errors.New("invalid edge")

	// ErrUnknownEdgeKind is wrapped by errors for extension edges whose kind
	// isn't registered or is malformed.
	ErrUnknownEdgeKind = errors.New("unknown edge kind")

	// ErrDuplicateOutput is wrapped by errors for generated files with more
	// than one generating rule.
	ErrDuplicateOutput = errors.New("file generated by more than one rule")

	// ErrOutOfPackage is wrapped by errors for facts an extension tried to
	// add about a target outside the package it is processing.
	ErrOutOfPackage = errors.New("fact about target outside current package")

	// ErrUnlinked is wrapped by Freeze errors when Requires edges remain.
	ErrUnlinked = errors.New("requires edges were not linked")

	// ErrFrozen is returned when a Builder is used after Freeze.
	ErrFrozen = errors.New("builder already frozen")

	// ErrCycle is wrapped by errors reporting dependency cycles.
	ErrCycle = errors.New("dependency cycle")

	// ErrUnresolvedImport is wrapped by errors for imports that no target
	// provides.
	ErrUnresolvedImport = errors.New("unresolved import")

	// ErrAmbiguousImport is wrapped by errors for imports that several
	// targets provide.
	ErrAmbiguousImport = errors.New("ambiguous import")
)
