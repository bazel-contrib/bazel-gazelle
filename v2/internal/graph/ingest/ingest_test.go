const buildFile = `
go_library(
    name = "lib",
    srcs = [
        "lib.go",
        ":gen.go",
    ],
    embed = [":inner"],
    deps = [
        "//other:other",
        "@ext//pkg",
        "@myrepo//self:self",
        ":kept",  # keep
    ] + select({
        "@rules_go//go/platform:linux": ["//linux"],
        "//conditions:default": [],
    }),
)

go_library(
    name = "inner",
    srcs = ["inner.go"],
)

go_library(
    name = "kept",
)

genrule(
    name = "gen",
    outs = ["gen.go"],
    tools = ["//tool"],
)

alias(
    name = "alias",
    actual = ":lib",
)
`

func load(t *testing.T) *rule.File {
	t.Helper()
	f, err := rule.LoadData("BUILD.bazel", "a", []byte(buildFile))
	if err != nil {
		t.Fatal(err)
	}
	return f
}

func summarize(g *graph.Graph, from graph.NodeKey) []string {
	var out []string
	for _, d := range g.DirectDeps(from, graph.DepQuery{}) {
		s := "depends_on " + d.Attr + " " + string(d.Node.Key)
		if d.Select != "" {
			s += " if " + d.Select
		}
		if d.Origin&graph.OriginKeep != 0 {
			s += " (keep)"
		}
		out = append(out, s)
	}
	for _, n := range g.Sources(from, "") {
		out = append(out, "contains "+string(n.Key))
	}
	for _, n := range g.EmbeddedBy(from) {
		out = append(out, "embeds "+string(n.Key))
	}
	for _, n := range g.Outputs(from) {
		out = append(out, "generates "+string(n.Key))
	}
	return out
}

func TestIngest(t *testing.T) {
	f := load(t)
	b, _ := graph.NewBuilder(graph.BuilderOptions{})
	var rules []Rule
	for _, r := range f.Rules {
		rules = append(rules, Rule{Rule: r, Lang: "go", Origin: graph.OriginExisting})
	}
	if err := Ingest(b, Package{RepoName: "myrepo", Pkg: "a", Rules: rules}); err != nil {
		t.Fatal(err)
	}
	g, err := b.Freeze()
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"depends_on deps t:@@//a:kept (keep)",
		"depends_on deps t:@@//other:other",
		"depends_on deps t:@@//self:self",
		"depends_on deps t:@ext//pkg:pkg",
		"depends_on deps t:@@//linux:linux if @rules_go//go/platform:linux",
		"depends_on embed t:@@//a:inner",
		"depends_on srcs g:@@//a:gen.go",
		"contains f:@@//a:lib.go",
	}
	if diff := cmp.Diff(want, summarize(g, RuleKey("a", "lib"))); diff != "" {
		t.Errorf("lib edges (-want +got):\n%s", diff)
	}
	if diff := cmp.Diff([]string{"depends_on tools t:@@//tool:tool", "generates g:@@//a:gen.go"}, summarize(g, RuleKey("a", "gen"))); diff != "" {
		t.Errorf("gen edges (-want +got):\n%s", diff)
	}
	if n, _ := g.Node(RuleKey("a", "lib")); n.RuleKind != "go_library" || n.Lang != "go" {
		t.Errorf("lib node = %+v", n)
	}
	// alias -> lib -> gen.go (generated by gen): Reachable follows AliasOf.
	if _, ok := g.Reachable(RuleKey("a", "alias"), RuleKey("a", "lib"), graph.DepQuery{}); !ok {
		t.Error("alias doesn't reach lib")
	}
}

// TestSkipAttrs checks that attributes Gazelle will re-derive are not
// ingested, except for kept values.
func TestSkipAttrs(t *testing.T) {
	f := load(t)
	b, _ := graph.NewBuilder(graph.BuilderOptions{})
	info := rule.KindInfo{ResolveAttrs: map[string]bool{"deps": true}}
	var rules []Rule
	for _, r := range f.Rules {
		rules = append(rules, Rule{Rule: r, Info: info, Origin: graph.OriginGenerated, SkipAttrs: info.ResolveAttrs})
	}
	if err := Ingest(b, Package{RepoName: "myrepo", Pkg: "a", Rules: rules}); err != nil {
		t.Fatal(err)
	}
	g, _ := b.Freeze()
	got := summarize(g, RuleKey("a", "lib"))
	var deps []string
	for _, s := range got {
		if strings.HasPrefix(s, "depends_on deps") {
			deps = append(deps, s)
		}
	}
	if diff := cmp.Diff([]string{"depends_on deps t:@@//a:kept (keep)"}, deps); diff != "" {
		t.Errorf("deps (-want +got):\n%s", diff)
	}

	// Observed ingestion after resolution adds the rest.
	b2, _ := graph.NewBuilder(graph.BuilderOptions{})
	if err := IngestAttrs(b2, Package{RepoName: "myrepo", Pkg: "a"}, rules, func(Rule) []string { return []string{"deps"} }); err != nil {
		t.Fatal(err)
	}
	g2, _ := b2.Freeze()
	if n := len(g2.DirectDeps(RuleKey("a", "lib"), graph.DepQuery{Attrs: []string{"deps"}})); n != 5 {
		t.Errorf("observed deps = %d, want 5", n)
	}
}

func TestLabelKey(t *testing.T) {
	for _, tc := range []struct {
		l    string
		want graph.NodeKey
	}{
		{":x", "t:@@//p:x"},
		{"//q", "t:@@//q:q"},
		{"@main//q:r", "t:@@//q:r"},
		{"@//q:r", "t:@@//q:r"},
		{"@@main//q:r", "t:@@main//q:r"},
		{"@other//q:r", "t:@other//q:r"},
	} {
		l, err := label.Parse(tc.l)
		if err != nil {
			t.Fatal(err)
		}
		if got := LabelKey(l, "main", "p"); got != tc.want {
			t.Errorf("LabelKey(%s) = %s, want %s", tc.l, got, tc.want)
		}
	}
}

func TestKeepVariants(t *testing.T) {
	f, err := rule.LoadData("BUILD.bazel", "a", []byte(`
x(
    name = "x",
    deps = select({
        "//cond:a": [
            "//kept_in_select",  # keep
            "//dropped",
        ],
    }),
    # keep
    data = ["//kept_attr"],
)

# keep
y(
    name = "y",
    deps = ["//kept_rule"],
)
`))
	if err != nil {
		t.Fatal(err)
	}
	b, _ := graph.NewBuilder(graph.BuilderOptions{})
	skip := map[string]bool{"deps": true, "data": true}
	var rules []Rule
	for _, r := range f.Rules {
		rules = append(rules, Rule{Rule: r, Origin: graph.OriginGenerated, SkipAttrs: skip})
	}
	if err := Ingest(b, Package{Pkg: "a", Rules: rules}); err != nil {
		t.Fatal(err)
	}
	g, _ := b.Freeze()
	want := []string{
		"depends_on data t:@@//kept_attr:kept_attr (keep)",
		"depends_on deps t:@@//kept_in_select:kept_in_select if //cond:a (keep)",
	}
	if diff := cmp.Diff(want, summarize(g, RuleKey("a", "x"))); diff != "" {
		t.Errorf("x (-want +got):\n%s", diff)
	}
	if !f.Rules[1].ShouldKeep() {
		t.Fatal("test setup: y is not kept")
	}
	if diff := cmp.Diff([]string{"depends_on deps t:@@//kept_rule:kept_rule (keep)"}, summarize(g, RuleKey("a", "y"))); diff != "" {
		t.Errorf("y (-want +got):\n%s", diff)
	}
}
